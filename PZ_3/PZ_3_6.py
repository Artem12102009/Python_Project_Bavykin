'''Дано целое число A. Проверить истинность высказывания: «Число A является
нечетным».'''

a = 0
try:
    a = int(input("Введите целоее число А: "))
except ValueError:
    print("Ошибка! Пожалуйста, введите целое число.")

b = a % 2 != 0
print(f"Высказывание 'Число {a} является нечётным' истинно? - {b}")
